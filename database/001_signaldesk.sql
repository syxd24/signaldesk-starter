-- SignalDesk: reproducible Supabase schema. Apply in a NEW Supabase project only.
-- No real prospect records, keys, or credentials are included.
create table if not exists public.gtm_companies (
 id uuid primary key default gen_random_uuid(),
 name text not null,
 domain text not null unique,
 qualification_status text not null default 'review' check (qualification_status in ('qualified','exclude','review')),
 hiring_signal text,
 signal_source_url text,
 research_summary text,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 constraint gtm_companies_domain_normalized check (domain=lower(btrim(domain)) and domain not like '%/%')
);
create table if not exists public.gtm_contacts (
 id uuid primary key default gen_random_uuid(),
 company_id uuid not null references public.gtm_companies(id),
 full_name text not null,
 job_title text,
 linkedin_url text,
 work_email text,
 email_verification text not null default 'unknown' check (email_verification in ('unknown','verified','unverified')),
 contact_status text not null default 'researched' check (contact_status in ('researched','ready','contacted','replied','meeting_booked','deal_won','deal_lost','bounced','do_not_contact')),
 last_contacted_at timestamptz,
 last_seen_at timestamptz not null default now(),
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 constraint gtm_contacts_identifier_required check (nullif(btrim(coalesce(work_email,'')),'') is not null or nullif(btrim(coalesce(linkedin_url,'')),'') is not null)
);
create unique index if not exists gtm_contacts_email_unique on public.gtm_contacts(lower(btrim(work_email))) where nullif(btrim(coalesce(work_email,'')),'') is not null;
create unique index if not exists gtm_contacts_linkedin_unique on public.gtm_contacts(regexp_replace(lower(btrim(linkedin_url)),'/+$','')) where nullif(btrim(coalesce(linkedin_url,'')),'') is not null;
create index if not exists gtm_contacts_company_idx on public.gtm_contacts(company_id);
create table if not exists public.gtm_outreach (
 id uuid primary key default gen_random_uuid(),
 contact_id uuid not null references public.gtm_contacts(id) on delete cascade,
 campaign_name text not null,
 step_number smallint not null check (step_number between 1 and 10),
 subject text,
 email_body text not null,
 delivery_status text not null default 'draft' check (delivery_status in ('draft','approved','sent','replied','bounced','cancelled')),
 reply_summary text,
 deal_stage text not null default 'none' check (deal_stage in ('none','meeting_booked','open','won','lost')),
 sent_at timestamptz,
 replied_at timestamptz,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 unique(contact_id,campaign_name,step_number)
);
create index if not exists gtm_outreach_contact_idx on public.gtm_outreach(contact_id);
create table if not exists public.gtm_import_log (
 id bigint generated by default as identity primary key,
 contact_id uuid references public.gtm_contacts(id),
 company_domain text,
 result text not null,
 source text not null default 'clay',
 created_at timestamptz not null default now()
);

alter table public.gtm_companies enable row level security;
alter table public.gtm_contacts enable row level security;
alter table public.gtm_outreach enable row level security;
alter table public.gtm_import_log enable row level security;
-- No public/anonymous/authenticated exposure. Only trusted back-end service role.
revoke all on public.gtm_companies,public.gtm_contacts,public.gtm_outreach,public.gtm_import_log from anon,authenticated;
grant select,insert,update,delete on public.gtm_companies,public.gtm_contacts,public.gtm_outreach,public.gtm_import_log to service_role;
grant usage,select on sequence public.gtm_import_log_id_seq to service_role;

create or replace function public.gtm_ingest_lead(payload jsonb)
returns jsonb language plpgsql security invoker set search_path=public
as $fn$
declare
 v_domain text := lower(btrim(coalesce(payload->>'company_domain','')));
 v_name text := nullif(btrim(coalesce(payload->>'company_name','')),'');
 v_email text := nullif(lower(btrim(coalesce(payload->>'work_email',''))),'');
 v_li text := nullif(regexp_replace(lower(btrim(coalesce(payload->>'linkedin_url',''))),'/+$',''),'');
 v_person text := nullif(btrim(coalesce(payload->>'full_name','')),'');
 v_company_id uuid;
 v_contact_id uuid;
 v_existing_status text;
 v_result text;
 v_campaign text := coalesce(nullif(btrim(coalesce(payload->>'campaign_name','')),''),'Sales Compensation Outreach');
 v_source text := coalesce(nullif(btrim(coalesce(payload->>'source','')),''),'clay');
begin
 v_domain := regexp_replace(v_domain,'^https?://(www[.])?','');
 v_domain := split_part(v_domain,'/',1);
 v_domain := regexp_replace(v_domain,'^www[.]','');
 if v_domain='' or v_name is null or v_person is null or (v_email is null and v_li is null) then
  return jsonb_build_object('result','INVALID_INPUT','reason','Need company name, domain, person name and work email or LinkedIn URL');
 end if;
 perform pg_advisory_xact_lock(hashtext(coalesce(v_email,v_li)));
 insert into public.gtm_companies(name,domain,qualification_status,hiring_signal,signal_source_url,research_summary)
 values (v_name,v_domain,
  case when lower(coalesce(payload->>'qualification_status','')) in ('qualified','exclude','review') then lower(payload->>'qualification_status') else 'review' end,
  nullif(payload->>'hiring_signal',''),nullif(payload->>'signal_source_url',''),nullif(payload->>'research_summary',''))
 on conflict(domain) do update set
  name=excluded.name,
  qualification_status=case when excluded.qualification_status='review' then gtm_companies.qualification_status else excluded.qualification_status end,
  hiring_signal=coalesce(excluded.hiring_signal,gtm_companies.hiring_signal),
  signal_source_url=coalesce(excluded.signal_source_url,gtm_companies.signal_source_url),
  research_summary=coalesce(excluded.research_summary,gtm_companies.research_summary),
  updated_at=now()
 returning id into v_company_id;

 select id,contact_status into v_contact_id,v_existing_status from public.gtm_contacts
 where (v_email is not null and lower(btrim(work_email))=v_email)
    or (v_li is not null and regexp_replace(lower(btrim(linkedin_url)),'/+$','')=v_li)
 order by case when v_li is not null and regexp_replace(lower(btrim(linkedin_url)),'/+$','')=v_li then 0 else 1 end
 limit 1 for update;
 if v_contact_id is null then
  insert into public.gtm_contacts(company_id,full_name,job_title,linkedin_url,work_email,email_verification)
  values(v_company_id,v_person,nullif(payload->>'job_title',''),v_li,v_email,
    case when lower(coalesce(payload->>'email_verification','')) in ('verified','unverified') then lower(payload->>'email_verification') else 'unknown' end)
  returning id into v_contact_id;
  v_result:='NEW';
 else
  update public.gtm_contacts set company_id=v_company_id,full_name=v_person,
   job_title=coalesce(nullif(payload->>'job_title',''),job_title),
   linkedin_url=coalesce(linkedin_url,v_li),work_email=coalesce(work_email,v_email),
   last_seen_at=now(),updated_at=now()
  where id=v_contact_id;
  if v_existing_status='do_not_contact' then
   v_result:='DO_NOT_CONTACT';
  elsif v_existing_status in ('contacted','replied','meeting_booked','deal_won','deal_lost','bounced')
    or exists(select 1 from public.gtm_outreach where contact_id=v_contact_id and delivery_status in ('sent','replied')) then
   v_result:='ALREADY_CONTACTED';
  else
   v_result:='EXISTING_RESEARCHED';
  end if;
 end if;
 if v_result in ('NEW','EXISTING_RESEARCHED')
    and not exists(select 1 from public.gtm_outreach where contact_id=v_contact_id and delivery_status in ('sent','replied')) then
  if nullif(btrim(coalesce(payload->>'email_1_body','')),'') is not null then
   insert into public.gtm_outreach(contact_id,campaign_name,step_number,subject,email_body)
   values(v_contact_id,v_campaign,1,nullif(payload->>'email_1_subject',''),payload->>'email_1_body')
   on conflict(contact_id,campaign_name,step_number) do nothing;
  end if;
  if nullif(btrim(coalesce(payload->>'email_2_body','')),'') is not null then
   insert into public.gtm_outreach(contact_id,campaign_name,step_number,subject,email_body)
   values(v_contact_id,v_campaign,2,nullif(payload->>'email_1_subject',''),payload->>'email_2_body')
   on conflict(contact_id,campaign_name,step_number) do nothing;
  end if;
 end if;
 insert into public.gtm_import_log(contact_id,company_domain,result,source)
 values(v_contact_id,v_domain,v_result,v_source);
 return jsonb_build_object('result',v_result,'contact_id',v_contact_id,'company_id',v_company_id,
                           'outreach_eligible',v_result in ('NEW','EXISTING_RESEARCHED'));
end
$fn$;
revoke all on function public.gtm_ingest_lead(jsonb) from public,anon,authenticated;
grant execute on function public.gtm_ingest_lead(jsonb) to service_role;
